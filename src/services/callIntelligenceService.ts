export function getAllCallIntelligence(): CallIntelligence[] {
  try {
    const raw = localStorage.getItem(INTELLIGENCE_STORAGE_KEY);
    if (!raw) {
      localStorage.setItem(INTELLIGENCE_STORAGE_KEY, JSON.stringify(SEED_CALL_INTELLIGENCE));
      return SEED_CALL_INTELLIGENCE;
    }
    const parsed = JSON.parse(raw);
    return Array.isArray(parsed) ? parsed : SEED_CALL_INTELLIGENCE;
  } catch {
    return SEED_CALL_INTELLIGENCE;
  }
}

export function getCallIntelligence(callId: string): CallIntelligence | null {
  const all = getAllCallIntelligence();
  return all.find((item) => item.call_id === callId) || null;
}

export function saveCallIntelligence(intelligence: CallIntelligence): void {
  try {
    const all = getAllCallIntelligence();
    const existingIndex = all.findIndex((i) => i.intelligence_id === intelligence.intelligence_id || i.call_id === intelligence.call_id);
    if (existingIndex >= 0) {
      all[existingIndex] = { ...all[existingIndex], ...intelligence };
    } else {
      all.unshift(intelligence);
    }
    localStorage.setItem(INTELLIGENCE_STORAGE_KEY, JSON.stringify(all));

    // Also link back to CallRecord in telephony storage
    const callRecords = getStoredCallRecords();
    const targetCall = callRecords.find((c) => c.call_id === intelligence.call_id);
    if (targetCall) {
      targetCall.intelligence = intelligence;
      targetCall.engagement_score = intelligence.engagement_score;
      targetCall.lead_temperature = intelligence.lead_temperature;
      targetCall.sentiment = intelligence.sentiment === 'Mixed' ? 'Neutral' : intelligence.sentiment;
      targetCall.interest_level =
        intelligence.interest_level === 'Neutral'
          ? 'Warm'
          : intelligence.interest_level === 'Not Interested' || intelligence.interest_level === 'Do Not Contact'
          ? 'Cold'
          : intelligence.interest_level;
      targetCall.summary = intelligence.summary;
      targetCall.notes = intelligence.crm_notes;
      targetCall.recommended_next_action = intelligence.next_best_action.action;
      targetCall.key_insights = intelligence.key_insights;
      if (!targetCall.raw_transcript && intelligence.raw_transcript) {
        targetCall.raw_transcript = intelligence.raw_transcript;
      }
      saveCallRecord(targetCall);
    }
  } catch (e) {
    console.error('Failed to save call intelligence:', e);
  }
}

