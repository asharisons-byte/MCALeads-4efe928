/**
 * Aggregated Objection Database Engine
 * Gathers, categorizes, and provides resolution strategies for every objection.
 */
export function getAggregatedObjections(filters?: {
  industry?: string;
  category?: string;
  minScore?: number;
}): AggregatedObjection[] {
  const allIntel = getAllCallIntelligence();

  const categories: ObjectionCategory[] = [
    'Price',
    'Timing',
    'Already Has Provider',
    'Too Busy',
    'Trust',
    'No Budget',
    'Not Interested',
    'Bad Previous Experience',
    'No Need',
    'Decision Maker Unavailable',
    'Other',
  ];

  const categoryMap: Record<
    ObjectionCategory,
    {
      count: number;
      industries: Set<string>;
      statements: string[];
      leads: Set<string>;
      lastDetected: string;
    }
  > = categories.reduce((acc, cat) => {
    acc[cat] = {
      count: 0,
      industries: new Set(),
      statements: [],
      leads: new Set(),
      lastDetected: '',
    };
    return acc;
  }, {} as any);

  let totalObjections = 0;

  allIntel.forEach((intel) => {
    (intel.objections || []).forEach((obj) => {
      const cat = obj.category || 'Other';
      if (!categoryMap[cat]) return;

      categoryMap[cat].count += 1;
      totalObjections += 1;
      if (intel.business_name) categoryMap[cat].industries.add(intel.business_name);
      if (intel.lead_id) categoryMap[cat].leads.add(intel.lead_id);
      if (obj.prospect_statement && !categoryMap[cat].statements.includes(obj.prospect_statement)) {
        categoryMap[cat].statements.push(obj.prospect_statement);
      }
      if (!categoryMap[cat].lastDetected || new Date(intel.generated_at) > new Date(categoryMap[cat].lastDetected)) {
        categoryMap[cat].lastDetected = intel.generated_at;
      }
    });
  });

  const responseStrategies: Record<ObjectionCategory, string> = {
    Price:
      'Reframe fee against single high-ticket job margin ($8,000+). Highlight 90-day ROI attribution and transparent lead tracking.',
    Timing:
      'Pivot immediately from synchronous live meetings to a 2-minute asynchronous video audit they can watch on their smartphone in the field.',
    'Already Has Provider':
      'Compliment existing relationship. Clarify that MCA does not replace web designers; we execute trade-specific local Map Pack rankings and citation architecture.',
    'Too Busy':
      'Validate seasonal peak. Explain that search ranking equity takes 30-60 days to mature, so starting now ensures high-margin bookings when slow season arrives.',
    Trust:
      'Share CCB verification data, Oregon-specific contractor case studies, and month-to-month terms with zero long-term lock-in.',
    'No Budget':
      'Offer localized Starter Verification package or contingency-backed local service ad launch.',
    'Not Interested':
      'Respectfully disengage, confirm if they wish to receive annual Oregon CCB regulatory updates, or mark Do Not Contact.',
    'Bad Previous Experience':
      'Differentiate by proving exclusive leads (never shared with 4 other contractors like HomeAdvisor) and providing recorded call access.',
    'No Need':
      'Highlight commercial or high-ticket service gap (e.g. panel upgrades vs outlets) where competitors are monopolizing search volume.',
    'Decision Maker Unavailable':
      'Confirm direct mobile number and best morning window (typically 7:00-8:00 AM before crews deploy) for a 3-minute executive briefing.',
    Other:
      'Ask clarifying open-ended discovery questions to uncover the underlying commercial hesitation.',
  };

  const results: AggregatedObjection[] = categories
    .map((cat) => {
      const data = categoryMap[cat];
      return {
        category: cat,
        count: data.count,
        percentage: totalObjections > 0 ? Math.round((data.count / totalObjections) * 100) : 0,
        top_industries: Array.from(data.industries).slice(0, 3),
        sample_statements: data.statements.slice(0, 3),
        recommended_response: responseStrategies[cat],
        last_detected: data.lastDetected || new Date().toISOString(),
        leads_affected: data.leads.size,
      };
    })
    .filter((o) => (filters?.category ? o.category === filters.category : true))
    .sort((a, b) => b.count - a.count);

  return results;
}

